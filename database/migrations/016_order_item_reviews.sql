ALTER TABLE review ADD COLUMN IF NOT EXISTS order_item_id integer REFERENCES order_item(order_item_id);

DO $$
BEGIN
    IF to_regclass('review_order_item_unique') IS NULL THEN
        -- Link legacy reviews only when the match is unique in both directions.
        WITH candidates AS (
            SELECT r.review_id, oi.order_item_id,
                   count(*) OVER (PARTITION BY r.review_id) AS items_per_review,
                   count(*) OVER (PARTITION BY oi.order_item_id) AS reviews_per_item
            FROM review r
            JOIN orders o ON o.user_id = r.user_id AND o.order_status = 'delivered'
                         AND o.order_date <= r.created_at
            JOIN order_item oi ON oi.order_id = o.order_id AND oi.book_id = r.book_id
            WHERE r.order_item_id IS NULL
        )
        UPDATE review r SET order_item_id = c.order_item_id
        FROM candidates c
        WHERE r.review_id = c.review_id AND c.items_per_review = 1 AND c.reviews_per_item = 1;

        ALTER TABLE review ADD CONSTRAINT review_order_item_unique UNIQUE (order_item_id);
    END IF;
END $$;

DROP INDEX IF EXISTS review_active_user_book_unique;

ALTER TABLE review_report DROP CONSTRAINT IF EXISTS review_report_reason_check;
ALTER TABLE review_report ADD CONSTRAINT review_report_reason_check
    CHECK (reason IN ('spam', 'harassment', 'personal_info', 'inappropriate', 'other'));

CREATE TABLE IF NOT EXISTS review_notification (
    notification_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id integer NOT NULL REFERENCES review(review_id),
    recipient_user_id integer NOT NULL REFERENCES users(user_id),
    book_title text NOT NULL,
    reason text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS review_notification_recipient_idx
    ON review_notification (recipient_user_id, notification_id DESC);
