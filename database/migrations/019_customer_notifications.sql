CREATE TABLE IF NOT EXISTS customer_notification (
    notification_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id integer NOT NULL REFERENCES users(user_id),
    event_type text NOT NULL,
    title text NOT NULL,
    message text NOT NULL,
    order_id integer REFERENCES orders(order_id),
    review_id integer REFERENCES review(review_id),
    book_title text,
    reason text,
    event_key text UNIQUE,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at timestamptz
);

INSERT INTO customer_notification
    (recipient_user_id, event_type, title, message, review_id, book_title, reason, event_key, created_at, read_at)
SELECT recipient_user_id, 'review_hidden', 'Đánh giá đã bị ẩn',
       format('Đánh giá của bạn về %s đã bị ẩn. Lý do: %s', book_title, reason),
       review_id, book_title, reason, 'legacy-review:' || notification_id, created_at, read_at
FROM review_notification
ORDER BY notification_id
ON CONFLICT (event_key) DO NOTHING;

CREATE INDEX IF NOT EXISTS customer_notification_recent_idx
    ON customer_notification (recipient_user_id, notification_id DESC);

CREATE INDEX IF NOT EXISTS customer_notification_unread_idx
    ON customer_notification (recipient_user_id) WHERE read_at IS NULL;
