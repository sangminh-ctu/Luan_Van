ALTER TABLE review
    ADD COLUMN IF NOT EXISTS visibility_status text NOT NULL DEFAULT 'visible'
        CHECK (visibility_status IN ('visible', 'hidden')),
    ADD COLUMN IF NOT EXISTS moderation_reason text,
    ADD COLUMN IF NOT EXISTS recheck_requested_at timestamptz,
    ADD COLUMN IF NOT EXISTS deleted_at timestamptz,
    ADD COLUMN IF NOT EXISTS version integer NOT NULL DEFAULT 1;

ALTER TABLE review DROP CONSTRAINT IF EXISTS review_user_book_unique;
DO $$
BEGIN
    IF to_regclass('review_order_item_unique') IS NULL THEN
        CREATE UNIQUE INDEX IF NOT EXISTS review_active_user_book_unique
            ON review (user_id, book_id) WHERE deleted_at IS NULL;
    END IF;
END $$;
CREATE INDEX IF NOT EXISTS review_public_book_recent_idx
    ON review (book_id, created_at DESC NULLS LAST, review_id DESC)
    WHERE visibility_status = 'visible' AND deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS review_report (
    report_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id integer NOT NULL REFERENCES review(review_id),
    reporter_user_id integer NOT NULL REFERENCES users(user_id),
    reason text NOT NULL CHECK (reason IN ('spam', 'harassment', 'personal_info', 'inappropriate', 'other')),
    description text CHECK (char_length(description) <= 1000),
    reported_rating integer NOT NULL CHECK (reported_rating BETWEEN 1 AND 5),
    reported_comment text,
    review_version integer NOT NULL,
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'resolved', 'rejected')),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at timestamptz,
    resolution text CHECK (resolution IN ('kept', 'hidden', 'author_deleted')),
    UNIQUE (review_id, reporter_user_id)
);
CREATE INDEX IF NOT EXISTS review_report_reporter_recent_idx
    ON review_report (reporter_user_id, created_at);

CREATE TABLE IF NOT EXISTS review_moderation_history (
    history_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id integer NOT NULL REFERENCES review(review_id),
    actor_user_id integer REFERENCES users(user_id),
    action text NOT NULL CHECK (action IN ('kept', 'hidden', 'restored', 'kept_hidden', 'review_requested', 'author_deleted')),
    reason text,
    review_version integer NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS review_moderation_history_review_idx
    ON review_moderation_history (review_id, history_id DESC);
